import { expect, test } from '@playwright/test'
import { cameraZoom, chooseBoardMenuItem, describeCanvas, dispatch, openApp, panelOfType, selectPanel } from './helpers'

const trigger = (page: import('@playwright/test').Page) => page.getByRole('button', { name: 'Board and panel options' })
const menu = (page: import('@playwright/test').Page) => page.getByRole('menu', { name: 'Board and panel options' })

test('one two-column menu shows disabled and selected states with keyboard navigation', async ({ page }) => {
  const consoleErrors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 900 })
  await openApp(page)
  await expect(trigger(page)).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Open panel view and layout actions' })).toHaveCount(0)
  await trigger(page).click()
  await expect(menu(page)).toBeVisible()
  await expect(menu(page).getByRole('group', { name: 'Panels', exact: true })).toBeVisible()
  await expect(menu(page).getByRole('group', { name: 'Board', exact: true })).toBeVisible()
  await expect(menu(page).getByRole('group', { name: 'Selected panel · none selected' })).toBeVisible()
  for (const name of ['Fit selected panel', 'Reset selected panel size', 'Hide selected panel']) {
    await expect(menu(page).getByRole('menuitem', { name })).toBeDisabled()
  }
  await expect(menu(page).getByRole('menuitem', { name: 'Fit all panels' })).toBeFocused()
  const beforeDisabledClick = await describeCanvas(page)
  await menu(page).getByRole('menuitem', { name: 'Hide selected panel' }).click({ force: true })
  expect(await describeCanvas(page)).toEqual(beforeDisabledClick)
  await expect(menu(page)).toBeVisible()
  await menu(page).getByRole('menuitem', { name: 'Fit all panels' }).focus()
  const desktopBox = await menu(page).boundingBox()
  console.log(`Desktop menu: ${Math.round(desktopBox!.width)} x ${Math.round(desktopBox!.height)} px at 1440 x 900`)
  await page.screenshot({ path: 'docs/screenshots/toolbar-menu-no-selection.png' })
  await page.keyboard.press('ArrowDown')
  await expect(menu(page).getByRole('menuitem', { name: 'Reset panel layout' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu(page).getByRole('menuitem', { name: 'Fit all panels' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(menu(page).getByRole('menuitem', { name: 'Duplicate board' })).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(menu(page).getByRole('menuitem', { name: 'Fit all panels' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('End')
  await expect(menu(page).getByRole('menuitem', { name: 'Delete board' })).toBeFocused()
  await page.keyboard.press('Home')
  await expect(menu(page).getByRole('menuitem', { name: 'Rename board' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu(page)).toBeHidden()
  await expect(trigger(page)).toBeFocused()

  const notes = await panelOfType(page, 'notes')
  await selectPanel(page, notes.panelId)
  await trigger(page).click()
  await expect(menu(page).getByRole('group', { name: 'Selected panel', exact: true })).toBeVisible()
  await expect(menu(page).getByRole('menuitem', { name: 'Hide selected panel' })).toBeEnabled()
  await page.screenshot({ path: 'docs/screenshots/toolbar-menu-selected.png' })
  await page.keyboard.press('End')
  await expect(menu(page).getByRole('menuitem', { name: 'Hide selected panel' })).toBeFocused()
  expect(consoleErrors).toEqual([])
})

test('narrow menu stacks its columns, shifts into the viewport, and scrolls vertically', async ({ page }) => {
  await page.setViewportSize({ width: 700, height: 550 })
  await openApp(page)
  await trigger(page).click()
  const panels = menu(page).getByRole('group', { name: 'Panels', exact: true })
  const board = menu(page).getByRole('group', { name: 'Board', exact: true })
  const panelBox = await panels.boundingBox()
  const boardBox = await board.boundingBox()
  const menuBox = await menu(page).boundingBox()
  expect(boardBox!.y).toBeGreaterThan(panelBox!.y + panelBox!.height)
  expect(menuBox!.x).toBeGreaterThanOrEqual(0)
  expect(menuBox!.x + menuBox!.width).toBeLessThanOrEqual(700)
  expect(menuBox!.y + menuBox!.height).toBeLessThanOrEqual(550)
  await page.screenshot({ path: 'docs/screenshots/toolbar-menu-narrow.png' })
  await page.keyboard.press('Escape')
  await expect(trigger(page)).toBeFocused()
  await page.setViewportSize({ width: 360, height: 520 })
  await trigger(page).click()
  const smallestBox = await menu(page).boundingBox()
  expect(smallestBox!.x).toBeGreaterThanOrEqual(0)
  expect(smallestBox!.x + smallestBox!.width).toBeLessThanOrEqual(360)
  expect(smallestBox!.y + smallestBox!.height).toBeLessThanOrEqual(520)
})

test('board actions keep rename, duplicate, export, import and delete behavior', async ({ page }, testInfo) => {
  await openApp(page)
  const picker = page.getByRole('combobox', { name: 'Open board' })
  page.once('dialog', (dialog) => void dialog.accept('Menu test board'))
  await chooseBoardMenuItem(page, 'Rename board')
  await expect(picker).toHaveAttribute('title', 'Menu test board')

  const downloadPromise = page.waitForEvent('download')
  await chooseBoardMenuItem(page, 'Export board')
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.board\.zip$/)
  const path = testInfo.outputPath(download.suggestedFilename())
  await download.saveAs(path)

  const chooserPromise = page.waitForEvent('filechooser')
  await chooseBoardMenuItem(page, 'Import board')
  page.once('dialog', (dialog) => void dialog.accept('Imported from menu'))
  await (await chooserPromise).setFiles(path)
  await expect(picker).toHaveAttribute('title', 'Imported from menu')
  await picker.click()
  const beforeDuplicate = await page.getByRole('listbox', { name: 'Boards' }).getByRole('option').count()
  await page.keyboard.press('Escape')
  await chooseBoardMenuItem(page, 'Duplicate board')
  await picker.click()
  await expect(page.getByRole('listbox', { name: 'Boards' }).getByRole('option')).toHaveCount(beforeDuplicate + 1)
  await page.keyboard.press('Escape')

  const beforeDelete = beforeDuplicate + 1
  let confirmed = false
  page.once('dialog', (dialog) => { confirmed = dialog.message().startsWith('Delete '); void dialog.accept() })
  await chooseBoardMenuItem(page, 'Delete board')
  expect(confirmed).toBe(true)
  await picker.click()
  await expect(page.getByRole('listbox', { name: 'Boards' }).getByRole('option')).toHaveCount(beforeDelete - 1)
})

test('panel actions keep fit, reset, hide and restore behavior', async ({ page }) => {
  await openApp(page)
  const notes = await panelOfType(page, 'notes')
  await dispatch(page, { kind: 'panel.resize', panelId: notes.panelId, w: notes.w + 120, h: notes.h + 90 })
  await selectPanel(page, notes.panelId)
  await trigger(page).click()
  await menu(page).getByRole('menuitem', { name: 'Reset selected panel size' }).click()
  await expect.poll(async () => {
    const current = await panelOfType(page, 'notes')
    return { w: current.w, h: current.h }
  }).toEqual({ w: notes.w, h: notes.h })

  await selectPanel(page, notes.panelId)
  await trigger(page).click()
  await menu(page).getByRole('menuitem', { name: 'Hide selected panel' }).click()
  await expect.poll(async () => (await panelOfType(page, 'notes')).visible).toBe(false)
  await trigger(page).click()
  await menu(page).getByRole('menuitem', { name: 'Restore Notes 1' }).click()
  await expect.poll(async () => (await panelOfType(page, 'notes')).visible).toBe(true)

  await dispatch(page, { kind: 'panel.move', panelId: notes.panelId, x: notes.x + 80, y: notes.y + 70 })
  await trigger(page).click()
  page.once('dialog', (dialog) => void dialog.accept())
  await menu(page).getByRole('menuitem', { name: 'Reset panel layout' }).click()
  await expect.poll(async () => {
    const current = await panelOfType(page, 'notes')
    return { x: current.x, y: current.y }
  }).toEqual({ x: notes.x, y: notes.y })

  const zoomBefore = await cameraZoom(page)
  await page.mouse.move(600, 600)
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, -300)
  await page.keyboard.up('Control')
  await expect.poll(() => cameraZoom(page)).not.toBe(zoomBefore)
  const zoomed = await cameraZoom(page)
  await trigger(page).click()
  await menu(page).getByRole('menuitem', { name: 'Fit all panels' }).click()
  await expect.poll(() => cameraZoom(page)).not.toBe(zoomed)

  await selectPanel(page, notes.panelId)
  const beforeFitSelected = await cameraZoom(page)
  await trigger(page).click()
  await menu(page).getByRole('menuitem', { name: 'Fit selected panel' }).click()
  await expect.poll(() => cameraZoom(page)).not.toBe(beforeFitSelected)
  expect((await describeCanvas(page)).panels.find((panel) => panel.panelId === notes.panelId)?.visible).toBe(true)
})

