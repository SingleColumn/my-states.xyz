test('the window targets its source panel and follows panel and board lifecycle', async ({ page }) => {
  await openApp(page)
  const first = await panelOfType(page, 'notes')
  await noteBodyOf(await shapeOf(page, first.panelId)).fill('First panel document')
  const second = await addPanelFromToolbar(page, 'notes')
  await dispatch(page, { kind: 'note.create', panelId: second.panelId })
  const secondPanel = await shapeOf(page, second.panelId)
  await noteBodyOf(secondPanel).fill('Second panel document')
  const manager = await openAnimations(secondPanel)
  await expect(manager).toHaveAttribute('data-source-panel-id', second.panelId)
  await dispatch(page, { kind: 'note.setContent', panelId: second.panelId, content: 'Updated second document' })
  await manager.getByRole('button', { name: 'Play in Writing Panel' }).click()
  await expect(secondPanel.locator('.animation-preview-host')).toContainText('Updated second document')
  await expect((await shapeOf(page, first.panelId)).locator('.animation-preview-host')).toHaveCount(0)
  await dispatch(page, { kind: 'panel.setVisible', panelId: second.panelId, visible: false })
  await expect(manager).toHaveCount(0)
  await dispatch(page, { kind: 'panel.setVisible', panelId: second.panelId, visible: true })
  const reopenedPanel = await shapeOf(page, second.panelId)
  await expect(reopenedPanel.locator('.animation-playback')).toHaveCount(0)
  await openAnimations(reopenedPanel)
  await dispatch(page, { kind: 'panel.remove', panelId: second.panelId })
  await expect(manager).toHaveCount(0)
  await openAnimations(await shapeOf(page, first.panelId))
  await createBoardFromToolbar(page, 'Another board')
  await expect(manager).toHaveCount(0)
  expect((await describeCanvas(page)).board?.name).toBe('Another board')
})

test('small and large windows and narrow and wide panels keep controls usable', async ({ page }) => {
  await openApp(page)
  const note = await panelOfType(page, 'notes')
  const panel = await shapeOf(page, note.panelId)
  const manager = await openAnimations(panel)
  await manager.focus()
  await page.keyboard.press('Delete')
  expect((await describeCanvas(page)).panels.length).toBe(3)
  const zoom = await cameraZoom(page)
  await manager.hover()
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, 240)
  await page.keyboard.up('Control')
  expect(await cameraZoom(page)).toBe(zoom)
  const before = (await describeCanvas(page)).panels.find(candidate => candidate.panelId === note.panelId)
  await dragLocator(page, manager.getByTestId('animation-window-drag'), { dx: 40, dy: 30 })
  const after = (await describeCanvas(page)).panels.find(candidate => candidate.panelId === note.panelId)
  expect({ x: after?.x, y: after?.y }).toEqual({ x: before?.x, y: before?.y })
  const resize = manager.getByRole('separator', { name: 'Resize animation window' })
  await dragLocator(page, resize, { dx: -220, dy: -200 })
  const small = await manager.boundingBox()
  expect(small).not.toBeNull()
  expect(small!.width).toBeGreaterThanOrEqual(390)
  expect(small!.height).toBeGreaterThanOrEqual(350)
  await expect(manager.getByRole('button', { name: 'Play in Writing Panel' })).toBeVisible()
  await manager.getByRole('button', { name: 'Duplicate' }).click()
  const css = manager.getByRole('textbox', { name: 'Animation CSS' })
  await expect(css).toBeVisible()
  await css.fill('abc')
  await css.focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  await expect(css).toHaveValue('')
  expect((await describeCanvas(page)).panels.length).toBe(3)
  await css.fill('.word { opacity: 1; }')
  await manager.screenshot({ path: 'test-results/animations-window-small.png' })
  await dragLocator(page, resize, { dx: 220, dy: 180 })
  const large = await manager.boundingBox()
  expect(large!.width).toBeGreaterThan(small!.width)
  expect(large!.height).toBeGreaterThan(small!.height)
  await manager.screenshot({ path: 'test-results/animations-css-editor.png' })
  await manager.getByRole('button', { name: 'Play in Writing Panel' }).click()
  await manager.getByRole('button', { name: 'Close animation window' }).click()
  for (const width of [320, 390, 600, 900]) {
    await dispatch(page, { kind: 'panel.resize', panelId: note.panelId, w: width, h: 650 })
    const toolbar = panel.getByRole('toolbar', { name: 'Animation options' })
    const positions = await toolbar.evaluate(element => {
      const outer = element.getBoundingClientRect()
      return [...element.querySelectorAll('button')].map(button => {
        const box = button.getBoundingClientRect()
        return { left: box.left, right: box.right, top: box.top, bottom: box.bottom, outerLeft: outer.left, outerRight: outer.right }
      })
    })
    expect(positions.every(item => item.left >= item.outerLeft && item.right <= item.outerRight)).toBe(true)
    expect(positions.every((item, index) => positions.slice(index + 1).every(other => item.right <= other.left || other.right <= item.left || item.bottom <= other.top || other.bottom <= item.top))).toBe(true)
  }
})

test('animation CSS rejects app selectors and external resources', async ({ page }) => {
  await openApp(page)
  const results = await page.evaluate(async () => {
    const { validateAnimationCss } = await import('/src/animations/css.ts' as string)
    return ['.word { color: red }', 'body { display: none }', '.word { background-image: url(https://example.com/x) }', '@import url(https://example.com/x);']
      .map(source => { try { validateAnimationCss(source); return true } catch { return false } })
  })
  expect(results).toEqual([true, false, false, false])
})

