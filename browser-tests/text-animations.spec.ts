import { test, expect, type Locator } from '@playwright/test'
import { addPanelFromToolbar, cameraZoom, createBoardFromToolbar, describeCanvas, dispatch, dragLocator, noteBodyOf, openApp, panelOfType, shapeOf, waitForCanvas } from './helpers'

async function openAnimations(panel: Locator) {
  const strip = panel.getByRole('toolbar', { name: 'Animation options' })
  if (!await strip.isVisible()) {
    await panel.getByRole('button', { name: 'Writing panel actions' }).click()
    await panel.page().getByRole('menuitemcheckbox', { name: 'Animations' }).click()
  }
  await expect(strip).toBeVisible()
  if (await strip.getByRole('button', { name: 'Show animation options' }).isVisible()) await strip.getByRole('button', { name: 'Show animation options' }).click()
  await strip.getByRole('button', { name: 'Animation settings' }).click()
  return panel.page().getByRole('dialog', { name: 'Animation management' })
}

test('the Animations action opens basic options below the header', async ({ page }) => {
  await openApp(page)
  const note = await panelOfType(page, 'notes')
  const panel = await shapeOf(page, note.panelId)
  const editor = noteBodyOf(panel)
  await editor.fill('A short document for preview')
  await expect(panel.getByRole('toolbar', { name: 'Animation options' })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Writing panel actions' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Animations' }).click()
  const strip = panel.getByRole('toolbar', { name: 'Animation options' })
  await expect(strip).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Animation management' })).toHaveCount(0)
  await strip.getByRole('combobox', { name: 'Animation' }).selectOption('random-illumination')
  await strip.getByRole('button', { name: 'Hide animation options' }).click()
  await expect(strip.getByRole('combobox', { name: 'Animation' })).toHaveCount(0)
  await strip.getByRole('button', { name: 'Show animation options' }).click()
  await expect(strip.getByRole('combobox', { name: 'Animation' })).toHaveValue('random-illumination')
  await panel.screenshot({ path: 'test-results/animations-basic-options.png' })
  for (const width of [320, 390, 600, 900]) {
    await dispatch(page, { kind: 'panel.resize', panelId: note.panelId, w: width, h: 650 })
    const positions = await strip.evaluate(element => {
      const outer = element.getBoundingClientRect()
      return [...element.querySelectorAll('button, select')].map(control => {
        const box = control.getBoundingClientRect()
        return { left: box.left, right: box.right, outerLeft: outer.left, outerRight: outer.right }
      })
    })
    expect(positions.every(item => item.left >= item.outerLeft && item.right <= item.outerRight)).toBe(true)
  }
  await dispatch(page, { kind: 'panel.resize', panelId: note.panelId, w: 440, h: 650 })
  const selectorBefore = await strip.getByRole('combobox', { name: 'Animation' }).boundingBox()
  await strip.getByRole('button', { name: 'Play animation', exact: true }).click()
  await expect(panel.locator('.animation-preview-host')).toContainText('A short document for preview')
  await expect(strip).toBeVisible()
  await expect(strip.getByRole('combobox', { name: 'Animation' })).toHaveValue('random-illumination')
  await expect(strip.getByRole('button', { name: 'Pause animation' })).toBeVisible()
  const selectorDuring = await strip.getByRole('combobox', { name: 'Animation' }).boundingBox()
  expect(selectorDuring!.x).toBe(selectorBefore!.x)
  expect(selectorDuring!.width).toBe(selectorBefore!.width)
  await expect(panel.getByRole('toolbar', { name: 'Animation playback' })).toHaveCount(0)
  await strip.getByRole('button', { name: 'Hide animation options' }).click()
  await expect(panel.locator('.animation-preview-host')).toBeVisible()
  await strip.getByRole('button', { name: 'Show animation options' }).click()
  await expect(strip.getByRole('combobox', { name: 'Animation' })).toHaveValue('random-illumination')
  await strip.getByRole('button', { name: 'Exit animation' }).click()
  await expect(strip.getByRole('button', { name: 'Play animation', exact: true })).toBeVisible()
  await expect(editor).toBeVisible()
  await strip.getByRole('button', { name: 'Close animation options' }).click()
  await expect(strip).toHaveCount(0)
})

test('start delay waits before playback and keeps its remaining time when paused', async ({ page }) => {
  await openApp(page)
  const note = await panelOfType(page, 'notes')
  const panel = await shapeOf(page, note.panelId)
  const editor = noteBodyOf(panel)
  await editor.fill('One two three four')
  const manager = await openAnimations(panel)
  const delay = manager.getByRole('slider', { name: 'Start delay (seconds)' })
  await delay.focus()
  await delay.press('Home')
  for (let index = 0; index < 4; index++) await delay.press('ArrowRight')
  await expect(delay).toHaveValue('2')
  await manager.getByRole('button', { name: 'Play in Writing Panel' }).click()
  const firstWord = panel.locator('.animation-preview-host .word').first()
  await expect(firstWord).toHaveAttribute('data-revealed', 'false')
  await page.waitForTimeout(400)
  await expect(firstWord).toHaveAttribute('data-revealed', 'false')
  const strip = panel.getByRole('toolbar', { name: 'Animation options' })
  await strip.getByRole('button', { name: 'Pause animation' }).click()
  await page.waitForTimeout(2100)
  await expect(firstWord).toHaveAttribute('data-revealed', 'false')
  await strip.getByRole('button', { name: 'Play animation', exact: true }).click()
  await page.waitForTimeout(500)
  await expect(firstWord).toHaveAttribute('data-revealed', 'false')
  await expect(firstWord).toHaveAttribute('data-revealed', 'true', { timeout: 3000 })
  await strip.getByRole('button', { name: 'Replay animation' }).click()
  await expect(panel.locator('.animation-preview-host .word').first()).toHaveAttribute('data-revealed', 'false')
  await strip.getByRole('button', { name: 'Exit animation' }).click()
  await expect(editor).toContainText('One two three four')
})

