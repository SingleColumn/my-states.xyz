import { test, expect } from '@playwright/test'
import { openApp, panelOfType, shapeOf, noteBodyOf, waitForCanvas } from './helpers'

test('preview, stop, replay, edit and restore a custom animation', async ({ page }) => {
  const { pageErrors } = await openApp(page)
  const note = await panelOfType(page, 'notes')
  const panel = await shapeOf(page, note.panelId)
  const editor = noteBodyOf(panel)
  await editor.fill('First words\n\nSecond paragraph')
  const original = await editor.innerText()
  await panel.getByRole('button', { name: 'Text animation' }).click()
  await panel.getByRole('button', { name: 'Preview / replay' }).click()
  const words = panel.locator('.animation-preview-host .word')
  await expect(words).toHaveCount(4)
  await expect(words.first()).toHaveAttribute('data-index', '0')
  await expect(words.last()).toHaveAttribute('data-index', '3')
  await expect(words.first()).toHaveAttribute('data-revealed', 'true')
  await panel.getByRole('button', { name: 'Stop' }).click()
  await panel.getByRole('button', { name: 'Preview / replay' }).click()
  await expect(words.first()).toHaveAttribute('data-revealed', 'false')
  await panel.getByRole('combobox', { name: 'Animation' }).selectOption('random-illumination')
  await panel.getByRole('button', { name: 'Preview / replay' }).click()
  await expect.poll(async () => panel.locator('.animation-preview-host .word[data-illuminated="true"]').count()).toBeGreaterThan(0)
  await panel.getByRole('button', { name: 'Stop' }).click()
  await expect(panel.locator('.animation-preview-host .word[data-illuminated="true"]')).toHaveCount(0)
  await panel.getByRole('button', { name: 'Duplicate' }).click()
  await panel.getByRole('textbox', { name: 'Animation CSS' }).fill('.word { color: red; }')
  await panel.getByRole('button', { name: 'Save animation' }).click()
  await expect(panel.getByRole('status')).toHaveText('Saved on this device.')
  expect(await words.first().evaluate(element => getComputedStyle(element).color)).toBe('rgb(255, 0, 0)')
  expect(await panel.locator('.card-title').evaluate(element => getComputedStyle(element).color)).not.toBe('rgb(255, 0, 0)')
  await panel.getByRole('button', { name: 'Edit note' }).click()
  await expect(editor).toBeVisible()
  expect(await editor.innerText()).toBe(original)
  await editor.click()
  await page.keyboard.press('End')
  await page.keyboard.type('!')
  await expect(editor).toContainText('!')
  await page.keyboard.press('Control+z')
  expect(await editor.innerText()).toBe(original)
  await page.reload()
  await waitForCanvas(page)
  const restored = await shapeOf(page, note.panelId)
  await restored.getByRole('button', { name: 'Text animation' }).click()
  await expect(restored.getByRole('combobox', { name: 'Animation' }).locator('option')).toHaveCount(3)
  expect(pageErrors).toEqual([])
})

test('CSS rejects app selectors and network resources', async ({ page }) => {
  await openApp(page)
  const results = await page.evaluate(async () => {
    const { validateAnimationCss } = await import('/src/animations/css.ts' as string)
    return ['.word { color: red }', 'body { display: none }', '.word { background-image: url(https://example.com/x) }', '@import url(https://example.com/x);']
      .map(source => { try { validateAnimationCss(source); return true } catch { return false } })
  })
  expect(results).toEqual([true, false, false, false])
})

test('empty and long notes preview without changing the canvas scroll target', async ({ page }) => {
  await openApp(page)
  const note = await panelOfType(page, 'notes')
  const panel = await shapeOf(page, note.panelId)
  await panel.getByRole('button', { name: 'Text animation' }).click()
  await panel.getByRole('button', { name: 'Preview / replay' }).click()
  await expect(panel.locator('.animation-preview-host .word')).toHaveCount(0)
  await panel.getByRole('button', { name: 'Edit note' }).click()
  await noteBodyOf(panel).fill(Array(1001).join('word '))
  await panel.getByRole('button', { name: 'Preview / replay' }).click()
  const host = panel.locator('.animation-preview-host')
  await expect(host.locator('.word')).toHaveCount(1000)
  expect(await host.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await host.hover()
  await page.mouse.wheel(0, 300)
  await expect.poll(() => host.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
})
